// Current language
let MG_currentLang = localStorage.getItem('mg_lang') || 'en';

function MG_t(key) {
  return MG_i18n[MG_currentLang]?.[key] || MG_i18n['en']?.[key] || key;
}

function MG_setLanguage(lang) {
  MG_currentLang = lang;
  localStorage.setItem('mg_lang', lang);
  MG_applyTranslations();
}

function MG_applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const translation = MG_t(key);
    if (translation !== key) {
      if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
        // skip, handled by placeholder
      } else {
        el.textContent = translation;
      }
    }
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const translation = MG_t(key);
    if (translation !== key) {
      el.placeholder = translation;
    }
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const translation = MG_t(key);
    if (translation !== key) {
      el.title = translation;
    }
  });
}

// Auto-apply on load
document.addEventListener('DOMContentLoaded', () => {
  MG_applyTranslations();
});